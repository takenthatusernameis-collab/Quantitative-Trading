"""Base strategy classes and interfaces."""

from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

import pandas as pd


@dataclass
class Signal:
    """Trading signal emitted by a strategy.

    The action is the order the strategy wants to place:

    - ``"buy"``: a buy order. It opens or adds to a long position. Against an
      open short it covers that short instead (up to the size of the short);
      a buy never flips a position.
    - ``"sell"``: a sell order. It reduces or closes a long position. It is
      rejected when no long position is held, so the framework never shorts a
      symbol through a plain sell.
    - ``"short"``: a short sale. It opens or adds to a short position. It is
      rejected while a long position is held; close the long first.
    - ``"hold"``: no order at all.

    Attributes:
        symbol: Ticker symbol the signal applies to.
        action: Direction of the signal ("buy", "sell", "short", or "hold").
        strength: Signal strength from 0.0 (no strength) to 1.0 (maximum).
        price: Limit price for the signal, if known.
        timestamp: Time the signal was created (defaults to now).
        metadata: Optional extra context keyed by arbitrary strings.

    Examples:
        Create a buy signal for a stock at market price::

            from quant_trading.strategies.base import Signal

            signal = Signal(symbol="AAPL", action="buy", price=150.0, strength=1.0)
            assert signal.action == "buy"
            assert signal.timestamp is not None

        Create a hold signal with no price::

            hold = Signal(symbol="AAPL", action="hold")
            assert hold.price is None

        Open a short position::

            short = Signal(symbol="AAPL", action="short", price=150.0)
            assert short.action == "short"

    """

    symbol: str
    action: str  # 'buy', 'sell', 'short', 'hold'
    strength: float = 1.0  # 0.0 to 1.0
    price: float | None = None
    timestamp: datetime | None = None
    metadata: dict[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        """Set default timestamp if not provided.

        If no timestamp is given, the current UTC time is assigned to ensure
        signals have a well-defined ordering.

        Returns:
            None.

        """
        if self.timestamp is None:
            self.timestamp = datetime.now()


@dataclass
class Position:
    """Current position in a symbol.

    Attributes:
        symbol: Ticker symbol the position is in.
        quantity: Position quantity (positive for long, negative for short).
        avg_price: Average entry price per unit.
        current_price: Latest market price per unit.
        unrealized_pnl: Unrealized profit and loss.
        realized_pnl: Realized profit and loss.

    Examples:
        >>> from quant_trading.strategies.base import Position
        >>> pos = Position(
        ...     symbol="AAPL",
        ...     quantity=100,
        ...     avg_price=150.0,
        ...     current_price=160.0,
        ...     unrealized_pnl=1000.0,
        ...     realized_pnl=500.0,
        ... )
        >>> pos.market_value
        16000.0
        >>> pos.pnl
        1500.0
        >>> flat = Position(symbol="AAPL")
        >>> flat.market_value
        0.0
        >>> flat.pnl
        0.0

    """

    symbol: str
    quantity: float = 0.0
    avg_price: float = 0.0
    current_price: float = 0.0
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0

    @property
    def market_value(self) -> float:
        """Current market value of the position.

        Returns:
            Quantity multiplied by the latest price.

        """
        return self.quantity * self.current_price

    @property
    def pnl(self) -> float:
        """Total profit and loss (realized plus unrealized).

        Returns:
            Sum of unrealized and realized PnL.

        """
        return self.unrealized_pnl + self.realized_pnl


class Strategy(ABC):
    """Abstract base class for trading strategies.

    Subclasses implement :meth:`generate_signals` to produce trading signals
    from market data and may override :meth:`validate_parameters` to enforce
    parameter constraints.

    Attributes:
        name: Human-readable strategy name.
        parameters: Dictionary of strategy parameters.
        signals: List of signals generated by the most recent call.
        positions: Dictionary of current positions keyed by symbol.

    Examples:
        >>> from quant_trading.strategies.base import Strategy, Signal
        >>> class MyStrategy(Strategy):
        ...     def generate_signals(self, data):
        ...         return [Signal(symbol="AAPL", action="buy", price=150.0)]
        >>> strategy = MyStrategy(name="My")
        >>> strategy.name
        'My'
        >>> strategy.parameters
        {}

    """

    description: str | None = None
    category: str | None = None

    def __init_subclass__(cls, **kwargs):
        super().__init_subclass__(**kwargs)
        if cls.description is None and cls.__doc__:
            cls.description = cls.__doc__.strip().splitlines()[0].rstrip(".")

    def __init__(self, name: str, parameters: dict[str, Any] | None = None):
        """Initialize the strategy.

        Args:
            name: Strategy name.
            parameters: Optional dictionary of strategy parameters.

        Returns:
            None.

        """
        self.name = name
        self.parameters = parameters or {}
        self.signals: list[Signal] = []
        self.positions: dict[str, Position] = {}

    @abstractmethod
    def generate_signals(self, data: dict[str, pd.DataFrame]) -> list[Signal]:
        """Generate trading signals from market data.

        Args:
            data: Dictionary mapping symbols to their price DataFrames.

        Returns:
            List of trading signals.

        """
        ...

    def validate_parameters(self) -> None:
        """Validate strategy parameters.

        The default implementation is a no-op. Subclasses should override
        this method to enforce constraints on ``self.parameters`` and raise
        ``ValueError`` when parameters are invalid.

        Returns:
            None.

        Raises:
            ValueError: If parameters are invalid.

        """
        return

    def update_positions(self, positions: dict[str, Position]) -> None:
        """Update internal position tracking.

        Args:
            positions: Current positions keyed by symbol.

        Returns:
            None.

        """
        self.positions = positions

    def get_parameters(self) -> dict[str, Any]:
        """Get a copy of the strategy parameters.

        Returns:
            Shallow copy of the parameters dictionary.

        """
        return self.parameters.copy()

    def set_parameter(self, key: str, value: Any) -> None:
        """Set a strategy parameter with validation and rollback.

        The new value is applied tentatively; if :meth:`validate_parameters`
        raises a ``ValueError`` the previous state is restored and the
        exception is re-raised. When the key did not previously exist it is
        removed from the parameters dictionary on rollback.

        Args:
            key: Parameter name.
            value: New parameter value.

        Returns:
            None.

        Raises:
            ValueError: If validation fails after the tentative update.

        """
        # Store old values for rollback on validation failure. The parameter
        # entry is restored only when the key existed before the tentative
        # update; a key that was absent is removed. Distinguishing "absent"
        # from "present with value None" matters because some strategies
        # legitimately store None in their parameters dict (e.g. an optional
        # exit period that defaults to the entry period).
        key_existed = key in self.parameters
        old_param_value = self.parameters.get(key)
        old_attr_value = getattr(self, key, None) if hasattr(self, key) else None

        # Tentatively update
        self.parameters[key] = value
        if hasattr(self, key):
            setattr(self, key, value)

        try:
            self.validate_parameters()
        except ValueError:
            # Rollback on validation failure
            if key_existed:
                self.parameters[key] = old_param_value
            else:
                self.parameters.pop(key, None)
            if hasattr(self, key):
                if old_attr_value is not None:
                    setattr(self, key, old_attr_value)
                else:
                    delattr(self, key)
            raise

    @classmethod
    def from_config(cls, config: dict[str, Any]) -> "Strategy":
        """Create strategy instance from configuration dictionary.

        Args:
            config: Dictionary with 'name' (optional), 'type' (strategy key),
                   and 'parameters' (dict of strategy parameters).

        Returns:
            Strategy instance.

        Raises:
            ValueError: If the config does not contain a 'type' key.

        """
        from quant_trading.strategies.factory import create_strategy

        strategy_type = config.get("type")
        if not strategy_type:
            raise ValueError("Strategy config must contain 'type' key")

        parameters = config.get("parameters", {})
        name = config.get("name", strategy_type)

        return create_strategy(strategy_type, name=name, **parameters)


class StrategyManager:
    """Manages multiple strategies.

    Attributes:
        strategies: Dictionary of strategies keyed by their name.

    Examples:
        >>> from quant_trading.strategies.base import Strategy, StrategyManager
        >>> import pandas as pd
        >>> class NoOpStrategy(Strategy):
        ...     def generate_signals(self, data):
        ...         return []
        >>> manager = StrategyManager()
        >>> manager.add_strategy(NoOpStrategy(name="Strat1"))
        >>> manager.add_strategy(NoOpStrategy(name="Strat2"))
        >>> set(manager.strategies) == {"Strat1", "Strat2"}
        True
        >>> signals = manager.generate_all_signals({"AAPL": pd.DataFrame()})
        >>> set(signals) == {"Strat1", "Strat2"}
        True

    """

    def __init__(self) -> None:
        """Initialize an empty strategy manager.

        Returns:
            None.

        """
        self.strategies: dict[str, Strategy] = {}

    def add_strategy(self, strategy: Strategy) -> None:
        """Add a strategy to the manager.

        If a strategy with the same name already exists it is overwritten.

        Args:
            strategy: Strategy instance to register.

        Returns:
            None.

        """
        self.strategies[strategy.name] = strategy

    def remove_strategy(self, name: str) -> None:
        """Remove a strategy by name.

        No error is raised if the strategy does not exist.

        Args:
            name: Strategy name to remove.

        Returns:
            None.

        """
        self.strategies.pop(name, None)

    def get_strategy(self, name: str) -> Strategy | None:
        """Get a strategy by name.

        Args:
            name: Strategy name to look up.

        Returns:
            The matching strategy, or None if not found.

        """
        return self.strategies.get(name)

    def generate_all_signals(self, data: dict[str, pd.DataFrame]) -> dict[str, list[Signal]]:
        """Generate signals from all registered strategies.

        Args:
            data: Dictionary mapping symbols to their price DataFrames.

        Returns:
            Dictionary mapping each strategy name to its list of signals.

        """
        signals: dict[str, list[Signal]] = {}
        for name, strategy in self.strategies.items():
            signals[name] = strategy.generate_signals(data)
        return signals


